"""Encyclopedia of Life species write-ups for Fauna.

EOL aggregates species knowledge from many sources. Fauna uses the free
classic API (no key needed) plus the key-gated TraitBank structured-data
API for "did you know" fact cards:

  search:   /api/search/1.0.json?q=<name>      -> EOL page IDs
  summary:  /api/pages/<id>/brief_summary.json -> English autogenerated
            summary from TraitBank data
  page:     /api/pages/1.0/<id>.json           -> English article text
            (when EOL has one) for the expandable "read more"
  cypher:   /service/cypher                     -> structured traits
            (needs an EOL API key, see README); curated into fact cards

The Cypher token comes from an EOL account: sign in at eol.org, email
hammockj AT si.edu asking for power-user status, then visit
eol.org/services/authenticate. It's pasted once in Fauna's Settings.

Results are cached 30 days in species_info_cache — descriptions barely
change, and page views must never hammer the API. The cache records a
hash of the API key so adding/changing the key refetches (to pick up
traits), plus the app version so upgrades refetch too (new card sources
must not sit behind a stale cache). Every public function is defensive:
failures return None, never raise — a missing write-up must never break
the page around it.
"""
from __future__ import annotations

import csv
import hashlib
import html
import io
import json
import os
import re
from datetime import datetime, timedelta

import httpx
from sqlalchemy.orm import Session

from app.models import SpeciesInfoCache
from app.version import VERSION

EOL_BASE = "https://eol.org"
CYPHER_URL = "https://eol.org/service/cypher"
CACHE_TTL = timedelta(days=30)
MAX_DESCRIPTION_CHARS = 1500
MAX_CARDS = 6


def _sanitize_no_proxy() -> None:
    """Drop malformed NO_PROXY entries (bracketed IPv6 literals like "[::1]")
    that crash httpx's proxy-env parsing. Same guard as app.inat."""
    for var in ("NO_PROXY", "no_proxy"):
        val = os.environ.get(var)
        if val and "[" in val:
            os.environ[var] = ",".join(p for p in val.split(",") if "[" not in p)


_sanitize_no_proxy()


def _key(name: str) -> str:
    return (name or "").strip().lower()


def _key_hash(api_key: str | None) -> str:
    return hashlib.sha256((api_key or "").encode()).hexdigest()[:16]


def search_page_id(scientific_name: str) -> int | None:
    """EOL page ID for an exact scientific-name match, else None."""
    query = (scientific_name or "").strip()
    if not query:
        return None
    resp = httpx.get(
        f"{EOL_BASE}/api/search/1.0.json",
        params={"q": query},
        timeout=15.0,
    )
    resp.raise_for_status()
    lowered = query.lower()
    results = resp.json().get("results", [])
    # exact match first ("Sciurus carolinensis"), then a prefix match
    # ("Sciurus carolinensis Gmelin, 1788") — never a longer taxon like
    # "Sciurus carolinensis extimus" when the species itself is there.
    for r in results:
        if (r.get("title") or "").lower() == lowered:
            return r.get("id")
    for r in results:
        title = (r.get("title") or "").lower()
        if title.startswith(lowered + " "):
            return r.get("id")
    return None


def fetch_brief_summary(page_id: int) -> str | None:
    """English autogenerated summary for an EOL page, else None."""
    resp = httpx.get(
        f"{EOL_BASE}/api/pages/{page_id}/brief_summary.json",
        timeout=15.0,
    )
    resp.raise_for_status()
    summary = (resp.json().get("brief_summary") or "").strip()
    return summary or None


def _strip_html(text: str) -> str:
    text = re.sub(r"<[^>]+>", " ", text or "")
    text = html.unescape(text)
    return re.sub(r"\s+", " ", text).strip()


# Boilerplate EOL prepends to some article texts, e.g.
# "More info for the term: fruit Red foxes are…" or
# "More info on this topic. This species can be…".
_BOILERPLATE = re.compile(
    r"^(More info for the terms?:\s+[a-z][^A-Z]*?(?=[A-Z])"
    r"|More info on this topic\.\s*)+"
)

# Subjects that read as general overviews, best first.
_OVERVIEW_SUBJECTS = ("brief summary", "comprehensive description", "description")


def _clean_description(text: str) -> str:
    text = _BOILERPLATE.sub("", _strip_html(text)).strip()
    return text


def fetch_description(page_id: int) -> dict | None:
    """Fullest English article text EOL has for the page, else None.

    Returns {"text", "source", "source_url"} — text is plain-text,
    truncated to a sensible length. Many taxa have no English text on EOL
    (their Wikipedia articles come in other languages); that's normal.
    """
    resp = httpx.get(
        f"{EOL_BASE}/api/pages/1.0/{page_id}.json",
        params={
            "images_per_page": 0,
            "videos_per_page": 0,
            "sounds_per_page": 0,
            "maps_per_page": 0,
            "texts_per_page": 30,
            "details": True,
        },
        timeout=20.0,
    )
    resp.raise_for_status()
    texts = [
        o
        for o in resp.json().get("taxonConcept", {}).get("dataObjects", [])
        if "Text" in str(o.get("dataType")) and o.get("language") == "en"
    ]
    if not texts:
        return None

    def _rank(o: dict) -> tuple:
        subjects = " ".join(o.get("subject") or []).lower()
        try:
            overview = _OVERVIEW_SUBJECTS.index(
                next(s for s in _OVERVIEW_SUBJECTS if s in subjects)
            )
        except StopIteration:
            overview = len(_OVERVIEW_SUBJECTS)
        return (overview, -len(o.get("description") or ""))

    best = sorted(texts, key=_rank)[0]
    text = _clean_description(best.get("description"))
    if len(text) < 80:  # stub, not worth showing
        return None
    if len(text) > MAX_DESCRIPTION_CHARS:
        text = text[:MAX_DESCRIPTION_CHARS].rsplit(" ", 1)[0] + "…"
    source = best.get("source") or ""
    source_name = "Wikipedia" if "wikipedia.org" in source else "Encyclopedia of Life"
    return {"text": text, "source": source_name, "source_url": source or None}


# predicate-name fragments -> (emoji, card label), in priority order.
CARD_RULES: list[tuple[tuple[str, ...], str, str]] = [
    (("body mass",), "⚖️", "Weight"),
    (("body length", "total length", "wingspan"), "📏", "Size"),
    (("trophic guild", "diet"), "🍽️", "Diet"),
    (("life span", "longevity", "maximum longevity"), "⏳", "Lifespan"),
    (("habitat",), "🏠", "Habitat"),
    (("litter size", "clutch size"), "🐣", "Young per birth"),
    (("gestation",), "🤰", "Gestation"),
    (("diel activity", "temporal activity"), "🌙", "Active"),
]


def _format_trait_value(row: dict) -> str | None:
    """Human-readable value from a Cypher trait row."""
    meas = (row.get("normal_measurement") or row.get("measurement") or "").strip()
    units = (row.get("normal_units") or row.get("units") or "").strip()
    if meas:
        try:  # tidy over-precise numbers: "253.48 mm" -> "253 mm"
            num = float(meas)
            meas = str(int(num)) if num.is_integer() else f"{num:.1f}".rstrip("0").rstrip(".")
        except ValueError:
            pass
        return f"{meas} {units}".strip()
    obj = (row.get("object") or "").strip()
    if obj:
        return obj
    lit = (row.get("literal") or "").strip()
    return lit or None


def _curate_cards(rows: list[dict]) -> list[dict]:
    """Pick the most interesting traits as 'did you know' cards."""
    cards: list[dict] = []
    used: set[str] = set()
    for fragments, emoji, label in CARD_RULES:
        for row in rows:
            pred = (row.get("predicate") or "").lower()
            if pred in used or not any(f in pred for f in fragments):
                continue
            value = _format_trait_value(row)
            if not value:
                continue
            cards.append({"icon": emoji, "label": label, "value": value})
            used.add(pred)
            break
        if len(cards) >= MAX_CARDS:
            break
    return cards


def fetch_traits(page_id: int, api_key: str) -> list[dict] | None:
    """'Did you know' fact cards from EOL's TraitBank (Cypher API).

    Returns a list of {"icon", "label", "value"} — [] when the taxon has
    no curated traits — or None when no key is configured or the service
    fails. Callers treat None as "no cards".
    """
    if not (api_key or "").strip():
        return None
    query = (
        "MATCH (t:Trait)<-[:trait|inferred_trait]-(p:Page {page_id: %d}), "
        "(t)-[:predicate]->(pred:Term) "
        "OPTIONAL MATCH (t)-[:object_term]->(obj:Term) "
        "OPTIONAL MATCH (t)-[:units_term]->(units:Term) "
        "OPTIONAL MATCH (t)-[:normal_units_term]->(nunits:Term) "
        "RETURN pred.name AS predicate, t.measurement AS measurement, "
        "units.name AS units, t.normal_measurement AS normal_measurement, "
        "nunits.name AS normal_units, obj.name AS object, t.literal AS literal "
        "LIMIT 60" % int(page_id)
    )
    resp = httpx.get(
        CYPHER_URL,
        params={"query": query, "format": "csv"},
        headers={"Authorization": f"JWT {api_key.strip()}"},
        timeout=25.0,
    )
    resp.raise_for_status()
    reader = csv.DictReader(io.StringIO(resp.text))
    rows = [dict(r) for r in reader if r.get("predicate")]
    return _curate_cards(rows)


def _read_cache(session: Session, key: str) -> dict | None:
    row = session.get(SpeciesInfoCache, key)
    if row is None:
        return None
    try:
        payload = json.loads(row.payload_json or "null")
    except (ValueError, TypeError):
        payload = None
    if not payload:
        return None
    fresh = bool(row.fetched_at) and datetime.utcnow() - row.fetched_at < CACHE_TTL
    return {"value": payload, "fresh": fresh}


def _write_cache(session: Session, key: str, payload: dict | None) -> None:
    row = session.get(SpeciesInfoCache, key)
    blob = json.dumps(payload) if payload else None
    if row is None:
        session.add(
            SpeciesInfoCache(
                taxon_key=key, fetched_at=datetime.utcnow(), payload_json=blob
            )
        )
    else:
        row.fetched_at = datetime.utcnow()
        row.payload_json = blob
    session.commit()


def get_species_info(
    session: Session, scientific_name: str, api_key: str | None = None
) -> dict | None:
    """Cached EOL write-up for a species.

    Returns {"summary", "eol_url", "page_id", "description", "traits"} or
    None. "traits" is a card list, [] when the taxon has none, None when
    no key is configured or the trait service failed. Never raises.
    """
    key = _key(scientific_name)
    if not key:
        return None
    current_hash = _key_hash(api_key)
    try:
        cached = _read_cache(session, key)
        if (
            cached
            and cached["fresh"]
            and cached["value"].get("key_hash") == current_hash
            and cached["value"].get("version") == VERSION
        ):
            return cached["value"]
        page_id = search_page_id(scientific_name)
        if not page_id:
            _write_cache(session, key, None)
            return None
        summary = fetch_brief_summary(page_id)
        if not summary:
            _write_cache(session, key, None)
            return None
        try:
            description = fetch_description(page_id)
        except Exception:
            description = None
        # Offline trait pack first: no key, no rate limits, instant — and
        # independent of EOL's servers. EOL's TraitBank stays as the
        # fallback for species the pack doesn't cover (insects, fish,
        # plants, ...).
        traits = None
        traits_source = None  # "local" when cards come from the bundled trait
        try:                  # pack (CC-licensed datasets), "eol" for TraitBank
            from app import trait_pack

            local_rows = trait_pack.fetch_local_trait_rows(session, scientific_name)
            if local_rows:
                traits = _curate_cards(local_rows)
                traits_source = "local" if traits else None
        except Exception:
            pass
        if not traits:
            try:
                traits = fetch_traits(page_id, api_key or "")
                traits_source = "eol" if traits else None
            except Exception:
                traits = None
        payload = {
            "summary": summary,
            "eol_url": f"{EOL_BASE}/pages/{page_id}",
            "page_id": page_id,
            "description": description,
            "traits": traits,
            "traits_source": traits_source,
            "key_hash": current_hash,
            "version": VERSION,
        }
        _write_cache(session, key, payload)
        return payload
    except Exception:
        return None
