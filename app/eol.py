"""Encyclopedia of Life species write-ups for Fauna.

EOL aggregates species knowledge from many sources. Fauna uses two free
endpoints (no API key needed):

  search:  /api/search/1.0.json?q=<name>      -> EOL page IDs
  summary: /api/pages/<id>/brief_summary.json -> English autogenerated
           summary from TraitBank data ("They are solitary, diurnal
           omnivores. Individuals are known to live for 288 months…")

The summaries are reliably English and HTML-free, unlike the per-language
Wikipedia texts on EOL pages. Results are cached 30 days in
species_info_cache — descriptions barely change, and page views must never
hammer the API. Every public function is defensive: failures return None,
never raise — a missing write-up must never break the page around it.
"""
from __future__ import annotations

import json
import os
from datetime import datetime, timedelta

import httpx
from sqlalchemy.orm import Session

from app.models import SpeciesInfoCache

EOL_BASE = "https://eol.org"
CACHE_TTL = timedelta(days=30)


def _sanitize_no_proxy() -> None:
    """Drop malformed NO_PROXY entries (bracketed IPv6 literals like "[::1]")
    that crash httpx's proxy-env parsing. Same guard as app.inat."""
    for var in ("NO_PROXY", "no_proxy"):
        val = os.environ.get(var)
        if val and "[" in val:
            os.environ[var] = ",".join(p for p in val.split(",") if "[" not in p)


_sanitize_no_proxy()


def _key(name: str) -> str:
    return (name or "").strip().lower()


def search_page_id(scientific_name: str) -> int | None:
    """EOL page ID for an exact scientific-name match, else None."""
    query = (scientific_name or "").strip()
    if not query:
        return None
    resp = httpx.get(
        f"{EOL_BASE}/api/search/1.0.json",
        params={"q": query},
        timeout=15.0,
    )
    resp.raise_for_status()
    lowered = query.lower()
    results = resp.json().get("results", [])
    # exact match first ("Sciurus carolinensis"), then a prefix match
    # ("Sciurus carolinensis Gmelin, 1788") — never a longer taxon like
    # "Sciurus carolinensis extimus" when the species itself is there.
    for r in results:
        if (r.get("title") or "").lower() == lowered:
            return r.get("id")
    for r in results:
        title = (r.get("title") or "").lower()
        if title.startswith(lowered + " "):
            return r.get("id")
    return None


def fetch_brief_summary(page_id: int) -> str | None:
    """English autogenerated summary for an EOL page, else None."""
    resp = httpx.get(
        f"{EOL_BASE}/api/pages/{page_id}/brief_summary.json",
        timeout=15.0,
    )
    resp.raise_for_status()
    summary = (resp.json().get("brief_summary") or "").strip()
    return summary or None


def _read_cache(session: Session, key: str) -> dict | None:
    row = session.get(SpeciesInfoCache, key)
    if row is None:
        return None
    try:
        payload = json.loads(row.payload_json or "null")
    except (ValueError, TypeError):
        payload = None
    if not payload:
        return None
    fresh = bool(row.fetched_at) and datetime.utcnow() - row.fetched_at < CACHE_TTL
    return {"value": payload, "fresh": fresh}


def _write_cache(session: Session, key: str, payload: dict | None) -> None:
    row = session.get(SpeciesInfoCache, key)
    blob = json.dumps(payload) if payload else None
    if row is None:
        session.add(
            SpeciesInfoCache(
                taxon_key=key, fetched_at=datetime.utcnow(), payload_json=blob
            )
        )
    else:
        row.fetched_at = datetime.utcnow()
        row.payload_json = blob
    session.commit()


def get_species_info(session: Session, scientific_name: str) -> dict | None:
    """Cached EOL write-up: {"summary", "eol_url", "page_id"} or None.

    Never raises; None means "no write-up available" and the species page
    simply omits the section.
    """
    key = _key(scientific_name)
    if not key:
        return None
    try:
        cached = _read_cache(session, key)
        if cached and cached["fresh"]:
            return cached["value"]
        page_id = search_page_id(scientific_name)
        if not page_id:
            _write_cache(session, key, None)
            return None
        summary = fetch_brief_summary(page_id)
        if not summary:
            _write_cache(session, key, None)
            return None
        payload = {
            "summary": summary,
            "eol_url": f"{EOL_BASE}/pages/{page_id}",
            "page_id": page_id,
        }
        _write_cache(session, key, payload)
        return payload
    except Exception:
        return None
